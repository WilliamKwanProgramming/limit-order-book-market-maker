#!/usr/bin/env python3
"""Interleaved A/B comparison of the two price-level containers of lob::OrderBook.

A is the default sorted std::vector (best price at the back); B is the std::map variant
(LOB_CORE_MAP_LEVELS=ON). Timing on a shared VM drifts with the machine's background load, so two
sequential benchmark runs cannot separate that drift from the effect of the container. This script
alternates the two binaries in counterbalanced blocks (AB, BA, AB, ...), pairs the A and B runs of
each block, and reports the ratio per block. Each invocation of bench_replay times one pass over
each synthetic stream (replay and matching), with the same seed, so both variants replay identical
streams (the checksums must agree, and the script fails if they do not).

Usage: compare_levels.py --vector-bin PATH --map-bin PATH --out FILE [--blocks 8]
                         [--messages 20000000] [--seed 42] [--max-load 1.3]
Standard library only.
"""
import argparse
import datetime
import os
import re
import statistics
import subprocess
import sys
import time


def load1():
    with open("/proc/loadavg") as f:
        return float(f.read().split()[0])


def run_once(binary, messages, seed):
    """One timed pass over each stream. Returns ({stream: ns/msg}, [checksums])."""
    out = subprocess.run(
        [binary, "--messages", str(messages), "--runs", "1", "--seed", str(seed)],
        capture_output=True, text=True, check=True).stdout
    ns = [float(x) for x in re.findall(r"per-run ns/msg:\s*([0-9.]+)", out)]
    checks = re.findall(r"checksum (\d+)", out)
    if len(ns) != 2 or len(checks) != 2:
        raise RuntimeError("unexpected bench_replay output:\n" + out)
    return {"replay": ns[0], "matching": ns[1]}, checks


def wait_for_quiet(max_load):
    for tries in range(121):
        load = load1()
        if load < max_load:
            print(f"1-minute load {load:.2f} < {max_load}: starting", file=sys.stderr)
            return load
        print(f"1-minute load {load:.2f} >= {max_load}: waiting 30 s", file=sys.stderr)
        time.sleep(30)
    raise SystemExit("machine stayed busy for 60 minutes; giving up")


def git_line():
    try:
        root = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True,
                              text=True, check=True).stdout.strip()
        head = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True,
                              check=True, cwd=root).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain", "--", "core"],
                               capture_output=True, text=True, check=True, cwd=root).stdout.strip()
        return f"{head} ({'with uncommitted changes in core/' if dirty else 'clean core/'})"
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--vector-bin", required=True)
    ap.add_argument("--map-bin", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--blocks", type=int, default=8)
    ap.add_argument("--messages", type=int, default=20_000_000)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--max-load", type=float, default=1.3)
    args = ap.parse_args()

    start_load = wait_for_quiet(args.max_load)
    bins = {"vector": args.vector_bin, "map": args.map_bin}
    rows = []  # (block, order, load, {variant: {stream: ns}})
    checks = {}
    for b in range(args.blocks):
        order = ["vector", "map"] if b % 2 == 0 else ["map", "vector"]
        res = {}
        load = load1()
        for variant in order:
            res[variant], ck = run_once(bins[variant], args.messages, args.seed)
            checks.setdefault(variant, ck)
            if ck != checks[variant]:
                raise SystemExit(f"{variant}: checksum changed between invocations")
        rows.append((b, order, load, res))
        print(f"block {b + 1}/{args.blocks} done (load at start {load:.2f})", file=sys.stderr)
    if checks["vector"] != checks["map"]:
        raise SystemExit("the two variants produced different checksums: not the same work")
    end_load = load1()

    lines = []
    lines.append("# Generated by core/bench/compare_levels.py; do not edit by hand.")
    lines.append(f"# command: {' '.join(sys.argv)}")
    lines.append(f"# git:     {git_line()}")
    lines.append(f"# date:    {datetime.datetime.now(datetime.timezone.utc):%Y-%m-%dT%H:%M:%SZ}")
    lines.append("# machine: shared 2-core cloud VM (another job may run concurrently); numbers are")
    lines.append("#          indicative only and will differ on other hardware.")
    lines.append("")
    lines.append(f"messages per stream: {args.messages}, seed {args.seed}, blocks {args.blocks}"
                 f" (counterbalanced AB/BA), one timed pass per stream per invocation")
    lines.append("A = sorted std::vector levels (default), B = std::map levels (LOB_CORE_MAP_LEVELS=ON)")
    lines.append(f"checksums identical across variants: yes ({checks['vector'][0]}, {checks['vector'][1]})")
    lines.append(f"loadavg at start: {start_load:.2f}, at end: {end_load:.2f}")
    lines.append("")
    for stream in ("replay", "matching"):
        lines.append(f"{stream} stream, ns/msg (lower is faster)")
        lines.append(f"  {'block':>5} {'order':>6} {'load':>5} {'A vector':>9} {'B map':>9} {'B/A':>6}")
        a_all, b_all, ratios = [], [], []
        for b, order, load, res in rows:
            a, bb = res["vector"][stream], res["map"][stream]
            a_all.append(a)
            b_all.append(bb)
            ratios.append(bb / a)
            lines.append(f"  {b + 1:>5} {'AB' if order[0] == 'vector' else 'BA':>6} {load:>5.2f}"
                         f" {a:>9.1f} {bb:>9.1f} {bb / a:>6.3f}")
        wins = sum(1 for r in ratios if r > 1.0)
        lines.append(f"  median A {statistics.median(a_all):.1f}   median B {statistics.median(b_all):.1f}"
                     f"   median of per-block B/A {statistics.median(ratios):.3f}"
                     f" (min {min(ratios):.3f}, max {max(ratios):.3f})")
        lines.append(f"  A faster than B in {wins} of {len(ratios)} blocks")
        lines.append("")
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
