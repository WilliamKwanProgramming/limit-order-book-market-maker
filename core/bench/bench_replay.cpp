namespace {

using namespace lob;

// Limit is a passive submit_limit; CrossLimit is a marketable one (same call, counted apart).
enum class Kind : std::uint8_t { Add, Delete, Reduce, Execute, Limit, CrossLimit, Market };
constexpr int kKinds = 7;
const char* const kKindNames[kKinds] = {
    "add_resting",           "cancel (deletion)", "reduce (partial)", "execute_resting",
    "submit_limit passive",  "submit_limit marketable", "submit_market"};

// Book shape seen by the generator, sampled every 1000 messages.
struct Shape {
  double orders = 0, levels = 0, samples = 0;
  void sample(const lob::OrderBook& book) {
    orders += static_cast<double>(book.order_count());
    levels += static_cast<double>(book.level_count(lob::Side::Bid) +
                                  book.level_count(lob::Side::Ask));
    samples += 1;
  }
};

// 16 bytes so that 20+ million messages fit comfortably in memory.
struct Msg {
  std::uint32_t id;
  std::int32_t price;
  std::int32_t qty;
  Kind kind;
  Side side;
};
static_assert(sizeof(Msg) == 16, "keep the message record compact");

constexpr std::size_t kTargetOrders = 300;
constexpr Price kStartPrice = 5'000'000;  // $500.00 in LOBSTER ticks

// Live order ids with O(1) random choice and removal (swap with last).
class LiveSet {
 public:
  void add(std::uint32_t id) {
    if (pos_.size() <= id) pos_.resize(static_cast<std::size_t>(id) * 2 + 16, kAbsent);
    pos_[id] = static_cast<std::uint32_t>(ids_.size());
    ids_.push_back(id);
  }
  void remove(std::uint32_t id) {
    const std::uint32_t p = pos_[id];
    ids_[p] = ids_.back();
    pos_[ids_[p]] = p;
    ids_.pop_back();
    pos_[id] = kAbsent;
  }
  std::size_t size() const { return ids_.size(); }
  std::uint32_t pick(Rng& rng) const { return ids_[rng.uniform_int(ids_.size())]; }

 private:
  static constexpr std::uint32_t kAbsent = UINT32_MAX;
  std::vector<std::uint32_t> ids_;
  std::vector<std::uint32_t> pos_;
};

// Probability of a new order, steered towards kTargetOrders resting orders.
double add_probability(std::size_t live) {
  const double p = 0.5 + 0.002 * (static_cast<double>(kTargetOrders) - static_cast<double>(live));
  return std::clamp(p, 0.40, 0.60);
}

// Passive price 0..19 ticks behind the touch of `side` (or one tick inside the spread).
Price passive_price(const OrderBook& book, Side side, Rng& rng) {
  const auto bid = book.best_bid();
  const auto ask = book.best_ask();
  const Price behind = rng.uniform_int(-1, 19);
  Price p;
  if (side == Side::Bid) {
    p = (bid ? bid->price : (ask ? ask->price - 1 : kStartPrice)) - behind;
    if (ask) p = std::min(p, ask->price - 1);
  } else {
    p = (ask ? ask->price : (bid ? bid->price + 1 : kStartPrice + 1)) + behind;
    if (bid) p = std::max(p, bid->price + 1);
  }
  return std::max<Price>(p, 1);
}

std::vector<Msg> make_replay_stream(std::size_t n, std::uint64_t seed, Shape& shape) {
  Rng rng = Rng::for_stream(seed, 1);
  OrderBook book;
  LiveSet live;
  std::vector<Fill> fills;
  std::vector<Msg> out;
  out.reserve(n);
  std::uint32_t next_id = 1;
  while (out.size() < n) {
    if (out.size() % 1000 == 0) shape.sample(book);
    const Side side = rng.bernoulli(0.5) ? Side::Bid : Side::Ask;
    if (live.size() < 20 || rng.bernoulli(add_probability(live.size()))) {
      const Price price = passive_price(book, side, rng);
      const Qty qty = rng.uniform_int(1, 500);
      book.add_resting(next_id, side, price, qty, 0);
      live.add(next_id);
      out.push_back({next_id++, static_cast<std::int32_t>(price), static_cast<std::int32_t>(qty),
                     Kind::Add, side});
    } else if (rng.bernoulli(0.82)) {  // cancellation: mostly full deletions
      const std::uint32_t id = live.pick(rng);
      const auto info = book.find(id);
      if (info->qty > 1 && rng.bernoulli(0.02)) {
        const Qty by = rng.uniform_int(1, info->qty - 1);
        book.reduce(id, by);
        out.push_back({id, 0, static_cast<std::int32_t>(by), Kind::Reduce, info->side});
      } else {
        book.cancel(id);
        live.remove(id);
        out.push_back({id, 0, 0, Kind::Delete, info->side});
      }
    } else {  // execution of the oldest order at the touch
      const auto front = book.front(side);
      if (!front) continue;
      const bool full = front->qty == 1 || rng.bernoulli(0.85);
      const Qty qty = full ? front->qty : rng.uniform_int(1, front->qty - 1);
      const auto id = static_cast<std::uint32_t>(front->id);
      book.execute_resting(id, qty, 0, fills);
      fills.clear();
      if (full) live.remove(id);
      out.push_back({id, 0, static_cast<std::int32_t>(qty), Kind::Execute, side});
    }
  }
  return out;
}

std::vector<Msg> make_matching_stream(std::size_t n, std::uint64_t seed, Shape& shape) {
  Rng rng = Rng::for_stream(seed, 2);
  OrderBook book;
  LiveSet live;
  std::vector<Fill> fills;
  std::vector<Msg> out;
  out.reserve(n);
  std::uint32_t next_id = 1;
  while (out.size() < n) {
    if (out.size() % 1000 == 0) shape.sample(book);
    const Side side = rng.bernoulli(0.5) ? Side::Bid : Side::Ask;
    const std::uint32_t id = next_id++;
    fills.clear();
    if (live.size() < 20 || rng.bernoulli(add_probability(live.size()))) {
      const Price price = passive_price(book, side, rng);
      const Qty qty = rng.uniform_int(1, 500);
      book.submit_limit(id, side, price, qty, 0, fills);
      live.add(id);
      out.push_back({id, static_cast<std::int32_t>(price), static_cast<std::int32_t>(qty),
                     Kind::Limit, side});
    } else if (rng.bernoulli(0.70)) {
      const std::uint32_t target = live.pick(rng);
      book.cancel(target);
      live.remove(target);
      out.push_back({target, 0, 0, Kind::Delete, side});
    } else {  // aggressive: market, or limit up to 3 ticks through the opposite touch
      const auto opp = book.best(opposite(side));
      if (!opp) continue;
      const Qty qty = rng.uniform_int(1, 500);
      SubmitResult r;
      Price price = 0;
      Kind kind = Kind::Market;
      if (rng.bernoulli(0.5)) {
        r = book.submit_market(id, side, qty, 0, fills);
      } else {
        kind = Kind::CrossLimit;
        const Price through = rng.uniform_int(0, 3);
        price = side == Side::Bid ? opp->price + through : opp->price - through;
        r = book.submit_limit(id, side, price, qty, 0, fills);
        if (r.resting > 0) live.add(id);
      }
      for (const Fill& f : fills) {
        if (f.resting_left == 0) live.remove(static_cast<std::uint32_t>(f.resting_id));
      }
      out.push_back({id, static_cast<std::int32_t>(price), static_cast<std::int32_t>(qty), kind,
                     side});
    }
  }
  return out;
}

struct RunResult {
  double seconds;
  std::uint64_t checksum;  // depends on every fill, so the work cannot be optimized away
};

RunResult run_once(const std::vector<Msg>& msgs) {
  OrderBook book;
  book.reserve(1 << 16, 4096);
  std::vector<Fill> fills;
  fills.reserve(4096);
  std::uint64_t checksum = 0;
  const auto t0 = std::chrono::steady_clock::now();
  for (const Msg& m : msgs) {
    fills.clear();
    switch (m.kind) {
      case Kind::Add: book.add_resting(m.id, m.side, m.price, m.qty, 0); break;
      case Kind::Delete: book.cancel(m.id); break;
      case Kind::Reduce: book.reduce(m.id, m.qty); break;
      case Kind::Execute: book.execute_resting(m.id, m.qty, 0, fills); break;
      case Kind::Limit:
      case Kind::CrossLimit: book.submit_limit(m.id, m.side, m.price, m.qty, 0, fills); break;
      case Kind::Market: book.submit_market(m.id, m.side, m.qty, 0, fills); break;
    }
    for (const Fill& f : fills) checksum += static_cast<std::uint64_t>(f.qty) * f.resting_id;
  }
  const auto t1 = std::chrono::steady_clock::now();
  checksum += book.order_count();
  return {std::chrono::duration<double>(t1 - t0).count(), checksum};
}

std::string read_first_line(const char* path, const char* prefix) {
  std::ifstream in(path);
  std::string line;
  while (std::getline(in, line)) {
    if (prefix == nullptr || line.rfind(prefix, 0) == 0) {
      if (prefix == nullptr) return line;
      const auto colon = line.find(':');
      return colon == std::string::npos ? line : line.substr(colon + 2);
    }
  }
  return "unknown";
}

void describe_stream(const char* name, const std::vector<Msg>& msgs, const Shape& shape) {
  std::size_t counts[kKinds] = {};
  for (const Msg& m : msgs) ++counts[static_cast<int>(m.kind)];
  std::printf("%s stream: %zu messages; book while generating: mean %.0f orders, "
              "mean %.1f price levels (both sides)\n",
              name, msgs.size(), shape.orders / shape.samples, shape.levels / shape.samples);
  for (int k = 0; k < kKinds; ++k) {
    if (counts[k] == 0) continue;
    std::printf("  %-24s %10zu  %5.1f%%\n", kKindNames[k], counts[k],
                100.0 * static_cast<double>(counts[k]) / static_cast<double>(msgs.size()));
  }
}

void benchmark(const char* name, const std::vector<Msg>& msgs, int runs) {
  std::vector<double> ns;
  std::uint64_t checksum = 0;
  bool consistent = true;
  for (int r = 0; r < runs; ++r) {
    const RunResult res = run_once(msgs);
    if (r == 0) checksum = res.checksum;
    consistent = consistent && res.checksum == checksum;
    ns.push_back(res.seconds * 1e9 / static_cast<double>(msgs.size()));
  }
  std::vector<double> sorted = ns;
  std::sort(sorted.begin(), sorted.end());
  const double best = sorted.front();
  const double median = sorted[sorted.size() / 2];  // runs is odd by default
  const double worst = sorted.back();
  std::printf("%s timing over %d runs (checksum %llu, %s across runs)\n", name, runs,
              static_cast<unsigned long long>(checksum), consistent ? "identical" : "DIFFERENT");
  std::printf("  per-run ns/msg:");
  for (const double x : ns) std::printf(" %.1f", x);
  std::printf("\n");
  std::printf("  %-8s %8s %14s\n", "", "ns/msg", "msgs/second");
  std::printf("  %-8s %8.1f %14.3e\n", "best", best, 1e9 / best);
  std::printf("  %-8s %8.1f %14.3e\n", "median", median, 1e9 / median);
  std::printf("  %-8s %8.1f %14.3e\n", "worst", worst, 1e9 / worst);
}

}  // namespace

int main(int argc, char** argv) {
  std::size_t messages = 20'000'000;
  int runs = 7;
  std::uint64_t seed = 42;
  for (int i = 1; i + 1 < argc; i += 2) {
    if (std::strcmp(argv[i], "--messages") == 0) messages = std::strtoull(argv[i + 1], nullptr, 10);
    else if (std::strcmp(argv[i], "--runs") == 0) runs = std::atoi(argv[i + 1]);
    else if (std::strcmp(argv[i], "--seed") == 0) seed = std::strtoull(argv[i + 1], nullptr, 10);
  }
  runs = std::max(runs, 1);

  std::printf("bench_replay: messages=%zu runs=%d seed=%llu\n", messages, runs,
              static_cast<unsigned long long>(seed));
  std::printf("compiler:     %s\n", LOB_BENCH_COMPILER);
  std::printf("build type:   %s\n", LOB_BENCH_BUILD_TYPE);
  std::printf("flags:        %s\n", LOB_BENCH_FLAGS);
  std::printf("levels:       %s\n", LOB_BENCH_LEVELS);
  std::printf("cpu:          %s (%s logical CPUs per /proc/cpuinfo 'siblings')\n",
              read_first_line("/proc/cpuinfo", "model name").c_str(),
              read_first_line("/proc/cpuinfo", "siblings").c_str());
  std::printf("loadavg at start: %s\n\n", read_first_line("/proc/loadavg", nullptr).c_str());

  {
    Shape shape;
    const std::vector<Msg> replay = make_replay_stream(messages, seed, shape);
    describe_stream("replay", replay, shape);
    benchmark("replay", replay, runs);
  }
  std::printf("\n");
  {
    Shape shape;
    const std::vector<Msg> matching = make_matching_stream(messages, seed, shape);
    describe_stream("matching", matching, shape);
    benchmark("matching", matching, runs);
  }
  std::printf("\nloadavg at end:   %s\n", read_first_line("/proc/loadavg", nullptr).c_str());
  return 0;
}
