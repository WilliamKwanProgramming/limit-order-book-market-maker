// Throughput benchmark for lob::OrderBook on synthetic, LOBSTER-like message streams.
//
// Two streams are generated in memory before any timing (lob::Rng, fixed seed):
//   replay   new limit orders (add_resting), full deletions and partial cancellations (cancel,
//            reduce) and executions of the front order at the touch (execute_resting).
//   matching passive limit orders, cancellations and aggressive orders: market orders and
//            marketable limit orders priced up to 3 ticks through the touch (submit_limit,
//            submit_market, cancel).
// New orders are placed 0 to DEPTH-1 ticks behind the touch on their own side (occasionally one
// tick inside the spread), sizes are uniform on 1..500, and the add probability is steered so the
// book holds about TARGET orders. By default DEPTH is 20 and TARGET is 300, a book of about 300
// orders over 41 to 51 price levels that fits in the CPU caches. The streams are generated by
// driving an OrderBook, so every message is valid when replayed. This is synthetic flow, not
// market data.
//
// Each timed run replays the whole stream into a fresh, pre-reserved book; the reported per-message
// cost therefore includes reading the message and dispatching on its type.
//
// Larger books. --target-orders and --depth change the size and the width of the book. With
// --prefill the stream starts with TARGET new orders (the book's initial state, all adds) that are
// replayed but NOT timed, followed by the --messages timed messages, so the timing describes a
// book that already holds its target number of orders instead of one that is still filling up.
// Without --prefill nothing changes from the original benchmark (same streams, same checksums).
// Book memory is about 48 bytes per order in the pool and 16 bytes per slot of an id index that
// is at most half full, so 10^5 orders take about 9 MB (more than the 2 MB L2 cache of the VM this
// was written on) and 10^6 orders about 82 MB (more than its 33 MB L3 cache).
//
// Usage: bench_replay [--messages N] [--runs R] [--seed S] [--target-orders K] [--depth D]
//                     [--prefill 0|1]
#include <algorithm>
#include <chrono>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <string>
#include <vector>

#include "lob/order_book.hpp"
