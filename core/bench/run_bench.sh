#!/usr/bin/env bash
# Rebuild bench_replay in Release with the default flags (no -march=native) and record its output
# under results/core/, together with the command, git commit and machine load.
#
#   core/bench/run_bench.sh                    -> results/core/bench.txt
#   core/bench/run_bench.sh --compare-levels   -> also results/core/bench_compare_levels.txt: the
#                                                 sorted-vector and std::map price-level containers
#                                                 run in alternating (AB/BA) blocks by
#                                                 core/bench/compare_levels.py, so that drift in the
#                                                 shared VM's speed cannot be mistaken for an effect
#   core/bench/run_bench.sh --book-sizes       -> ONLY results/core/bench_book_size.txt: the same
#                                                 streams with books of about 300, 10^4, 10^5 and
#                                                 10^6 resting orders (--target-orders, --depth and
#                                                 --prefill of bench_replay; the build-up of the book
#                                                 is replayed but not timed), one run of
#                                                 bench_replay each, then a summary table made by
#                                                 core/bench/book_size_table.py
#
# The machine this was written on is a shared 2-core cloud VM, so the script waits until the
# 1-minute load average is below MAX_LOAD (default 1.3) before each benchmark and records the load.
# bench_replay also measures how much CPU other processes used while it ran (its "interference:"
# line); --book-sizes reruns a configuration when that exceeds MAX_OTHER CPUs (default 0.25).
# Extra arguments after the flags are passed to bench_replay (defaults: 20M messages, 7 runs,
# seed 42).
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$repo"

compare_levels=0
book_sizes=0
while [[ "${1:-}" == "--compare-levels" || "${1:-}" == "--book-sizes" ]]; do
  [[ "$1" == "--compare-levels" ]] && compare_levels=1
  [[ "$1" == "--book-sizes" ]] && book_sizes=1
  shift
done
bench_args=("$@")
max_load="${MAX_LOAD:-1.3}"
max_other="${MAX_OTHER:-0.25}"
cxx="${CXX:-g++}"

wait_for_quiet_machine() {
  local tries=0
  while true; do
    local load
    load="$(cut -d' ' -f1 /proc/loadavg)"
    if awk -v l="$load" -v m="$max_load" 'BEGIN { exit !(l < m) }'; then
      echo "1-minute load ${load} < ${max_load}: starting" >&2
      return 0
    fi
    tries=$((tries + 1))
    if ((tries > 120)); then
      echo "load still ${load} after 60 minutes; giving up" >&2
      exit 1
    fi
    echo "1-minute load ${load} >= ${max_load}: waiting 30 s" >&2
    sleep 30
  done
}

# build_and_run <build dir> <output file> [extra cmake args...]
build_and_run() {
  local build_dir="$1" out="$2"
  shift 2
  CXX="$cxx" cmake -S . -B "$build_dir" -G Ninja -DCMAKE_BUILD_TYPE=Release -DLOB_NATIVE=OFF \
    -DLOB_SANITIZE=OFF -DLOB_BUILD_TESTS=OFF "$@" >/dev/null
  cmake --build "$build_dir" -j2 --target bench_replay >/dev/null
  wait_for_quiet_machine
  mkdir -p "$(dirname "$out")"
  {
    echo "# Generated by core/bench/run_bench.sh; do not edit by hand."
    echo "# command: $build_dir/core/bench_replay ${bench_args[*]:-}"
    echo "# cmake:   -DCMAKE_BUILD_TYPE=Release -DLOB_NATIVE=OFF $*"
    echo "# git:     $(git rev-parse HEAD 2>/dev/null || echo unknown)" \
      "($(git status --porcelain -- core 2>/dev/null | grep -q . && echo 'with uncommitted changes in core/' || echo 'clean core/'))"
    echo "# date:    $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "# machine: shared 2-core cloud VM (another job may run concurrently); numbers are"
    echo "#          indicative only and will differ on other hardware."
    echo
    "$build_dir/core/bench_replay" "${bench_args[@]}"
  } >"$out"
  echo "wrote $out" >&2
}

# Book-size sweep: (target orders, depth in ticks) pairs with about 50 orders per price level and
# side once the book is large (the smallest pair is the default benchmark's book).
book_size_sweep() {
  local build_dir=build-core-bench out=results/core/bench_book_size.txt
  CXX="$cxx" cmake -S . -B "$build_dir" -G Ninja -DCMAKE_BUILD_TYPE=Release -DLOB_NATIVE=OFF \
    -DLOB_SANITIZE=OFF -DLOB_BUILD_TESTS=OFF >/dev/null
  cmake --build "$build_dir" -j2 --target bench_replay >/dev/null
  local tmp
  tmp="$(mktemp -d)"
  local i=0
  local -a pairs=("300 20" "10000 100" "100000 1000" "1000000 10000")
  for pair in "${pairs[@]}"; do
    i=$((i + 1))
    read -r target depth <<<"$pair"
    # Rerun a configuration (up to 6 times) if other processes used more than MAX_OTHER CPUs on
    # average while it ran (the load average cannot tell the benchmark's own load from another job's).
    for attempt in 1 2 3 4 5 6; do
      wait_for_quiet_machine
      "$build_dir/core/bench_replay" "${bench_args[@]}" --target-orders "$target" --depth "$depth" \
        --prefill 1 >"$tmp/run_$i.txt"
      other="$(sed -n 's/^interference: *other processes used \([0-9.]*\) CPUs.*/\1/p' "$tmp/run_$i.txt")"
      if [[ -z "$other" ]] || awk -v o="$other" -v m="$max_other" 'BEGIN { exit !(o < m) }'; then
        break
      fi
      echo "other processes used $other CPUs during the $target-order run (limit $max_other):" \
        "attempt $attempt of 6" >&2
    done
  done
  mkdir -p "$(dirname "$out")"
  {
    echo "# Generated by core/bench/run_bench.sh --book-sizes; do not edit by hand."
    echo "# command: $build_dir/core/bench_replay ${bench_args[*]:-} --target-orders K --depth D --prefill 1"
    echo "#          for (K, D) in 300/20, 10000/100, 100000/1000, 1000000/10000"
    echo "# cmake:   -DCMAKE_BUILD_TYPE=Release -DLOB_NATIVE=OFF"
    echo "# git:     $(git rev-parse HEAD 2>/dev/null || echo unknown)" \
      "($(git status --porcelain -- core 2>/dev/null | grep -q . && echo 'with uncommitted changes in core/' || echo 'clean core/'))"
    echo "# date:    $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "# machine: shared 2-core cloud VM (another job may run concurrently); numbers are"
    echo "#          indicative only and will differ on other hardware."
    echo
    echo "## Summary (core/bench/book_size_table.py; medians over the runs below)"
    echo
    python3 core/bench/book_size_table.py "$tmp"/run_*.txt
    echo
    for ((j = 1; j <= i; j++)); do
      echo "## Run $j of $i"
      echo
      cat "$tmp/run_$j.txt"
      echo
    done
  } >"$out"
  rm -rf "$tmp"
  echo "wrote $out" >&2
}

if ((book_sizes)); then
  book_size_sweep
  exit 0
fi

build_and_run build-core-bench results/core/bench.txt
if ((compare_levels)); then
  # Build the std::map variant (not run on its own) and alternate the two binaries.
  CXX="$cxx" cmake -S . -B build-core-bench-map -G Ninja -DCMAKE_BUILD_TYPE=Release -DLOB_NATIVE=OFF \
    -DLOB_SANITIZE=OFF -DLOB_BUILD_TESTS=OFF -DLOB_CORE_MAP_LEVELS=ON >/dev/null
  cmake --build build-core-bench-map -j2 --target bench_replay >/dev/null
  python3 core/bench/compare_levels.py --vector-bin build-core-bench/core/bench_replay \
    --map-bin build-core-bench-map/core/bench_replay --out results/core/bench_compare_levels.txt \
    --max-load "$max_load"
fi
